/**
 * Traduz uma mensagem de falha do axe-core linha por linha.
 * @param {string} texto
 * @returns {string}
 */
export function traduzirFalhaSummary(texto) {
  if (!texto) return '';
  let resultado = texto;
  for (const [en, ptbr] of Object.entries(traducaoFalhaSummary)) {
    resultado = resultado.split(en).join(ptbr);
  }
  return resultado;
}

/**
 * Traduz a descrição de uma violação do axe-core.
 * @param {string} texto
 * @returns {string}
 */
export function traduzirDescricao(texto) {
  return traducaoDescricao[texto] || texto;
}

/**
 * Traduz o campo help de uma violação do axe-core.
 * @param {string} texto
 * @returns {string}
 */
export function traduzirHelp(texto) {
  return traducaoHelp[texto] || texto;
}
